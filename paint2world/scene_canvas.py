"""Stage -0.5c: 3D spatial-dependency graph and scene canvas.

The scene canvas is Paint2World's explicit 3D scaffold: it takes the objects
generated by the TripoSplat stage, establishes the **spatial dependency
relations** between them (who supports whom, who is in front of whom, who is
adjacent to whom, who rests on the ground), fits a ground plane, snaps
floating objects onto their supports, and exposes the composed scene as one
renderable Gaussian set.

The canvas is what turns a bag of per-object 3D models into a *scene*:

  * Stage 0 consumes the canvas-composited depth map as its geometry control,
    so generated frames respect object occlusion boundaries.
  * Stage 3.2 trains the scene Gaussians with **object-rigid anchors** — each
    object moves as a whole via a learnable SE(3) delta — plus a
    **relation-preservation loss** that keeps supports/rests-on contacts
    intact during optimisation.

All geometry lives in the painting-camera frame (x right, y down, z forward);
``painting_c2w`` maps the canvas into the pipeline's world frame.
"""


# ---------------------------------------------------------------------------
# Ground plane
# ---------------------------------------------------------------------------

def fit_ground_plane(
    points: torch.Tensor,  # (N, 3) camera-space points
    bottom_fraction: float,
) -> dict:
    """Fit a ground plane y = a*x + b*z + c to the scene's lowest points.

    ``bottom_fraction`` of the points with the largest y (y points down) are
    treated as ground samples. Returns the plane coefficients and the ground
    extent (for canvas drawing).
    """
    n = points.shape[0]
    if n < 8:
        return {"a": 0.0, "b": 0.0, "c": float(points[:, 1].max().item()) if n else 0.0}
    k = max(8, int(n * bottom_fraction))
    idx = torch.topk(points[:, 1], k=k, largest=True).indices
    gp = points[idx]
    A = torch.cat([gp[:, 0:1], gp[:, 2:3], torch.ones(k, 1, device=points.device)], dim=1)
    y = gp[:, 1:2]
    sol = torch.linalg.lstsq(A, y).solution  # (3, 1)
    a, b, c = (float(sol[0].item()), float(sol[1].item()), float(sol[2].item()))
    return {"a": a, "b": b, "c": c}


def ground_y_at(plane: dict, x: float, z: float) -> float:
    return plane["a"] * x + plane["b"] * z + plane["c"]


# ---------------------------------------------------------------------------
# Object layout helpers (axis-aligned boxes in camera space)
# ---------------------------------------------------------------------------

def _obb(points: torch.Tensor) -> dict:
    mn, mx = points.min(dim=0).values, points.max(dim=0).values
    return {
        "min": mn.tolist(),
        "max": mx.tolist(),
        "center": ((mn + mx) * 0.5).tolist(),
        "extent": (mx - mn).tolist(),
    }


def _horizontal_overlap_1d(a_min, a_max, b_min, b_max) -> float:
    return max(0.0, min(a_max, b_max) - max(a_min, b_min))


def _mask_overlap(mask_a: np.ndarray, mask_b: np.ndarray) -> float:
    inter = np.logical_and(mask_a, mask_b).sum()
    if inter == 0:
        return 0.0
    return float(inter) / float(min(mask_a.sum(), mask_b.sum()))



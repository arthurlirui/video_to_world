def build_scene_canvas(
    cfg: SceneCanvasConfig,
    image: np.ndarray,  # (H, W, 3) uint8
    depth: np.ndarray,  # (H, W) in [0, 1]
    seg: dict,  # object_segmentation output
    ts: dict,  # triposplat.generate_objects output
    painting_c2w: torch.Tensor,
    out_dir: Optional[str] = None,
    strokes: Optional[np.ndarray] = None,
) -> dict:
    """Stage -0.5c driver: objects + background -> dependency graph -> canvas.

    Returns ``{"canvas": SceneCanvas, "relations": [...], "placement": {...},
    "background_gaussians": N, "out_dir": ...}``.
    """
    device = torch.device("cpu")
    rgb = torch.from_numpy(image.copy()).float().permute(2, 0, 1) / 255.0
    dep = torch.from_numpy(depth.copy()).float().unsqueeze(0)

    canvas = SceneCanvas(painting_c2w=painting_c2w)
    for entry in ts["objects"]:
        meta = next(o for o in seg["objects"] if o["id"] == entry["id"])
        canvas.add_object(entry, meta["mask"])

    # --- Background: pixels belonging to no object ---
    labels = torch.from_numpy(seg["labels"]).long()
    bg_mask = labels == 0
    if bg_mask.any():
        from .triposplat import lift_object_to_camera_space

        bg_pts, bg_cols = lift_object_to_camera_space(
            rgb, dep, bg_mask, max_points=3000
        )
        canvas.set_background(init_gaussians_from_canonical(bg_pts, bg_cols))
    else:
        canvas.set_background(
            {"position": torch.zeros(0, 3), "sh_dc": torch.zeros(0, 3),
             "opacity": torch.zeros(0), "scale": torch.zeros(0, 3),
             "rotation": torch.zeros(0, 4)}
        )

    # --- Ground plane from all canvas points ---
    all_pts = [o["gaussians"]["position"].detach() for o in canvas.objects if o["num_gaussians"] > 0]
    all_pts.append(canvas.background["position"].detach())
    all_pts = torch.cat(all_pts, dim=0)
    canvas.ground = fit_ground_plane(all_pts, bottom_fraction=cfg.ground_plane_weight * 0.25)

    # --- Dependency graph + physical placement ---
    canvas.compute_relations(cfg)
    placement = canvas.snap_objects_to_supports(cfg)

    # --- Stroke labels: project the camera-frame Gaussians into the painting
    # view and read the stroke map (same convention as the aligned-cloud path).
    if strokes is not None:
        g_all = canvas.canvas_gaussians_camera()
        if g_all["position"].shape[0] > 0:
            g_lbl = {"position": g_all["position"]}
            assign_stroke_labels(g_lbl, g_all["position"], strokes)
            canvas.stroke_labels = g_lbl["stroke_label"]

    if out_dir:
        canvas.save(out_dir)
        _plot_layout(canvas, os.path.join(out_dir, "layout.png"))
        # Canvas depth visualisation.
        from .painting_analysis import _save_gray

        H, W = image.shape[:2]
        _save_gray(
            canvas.canvas_depth(H, W).cpu().numpy(),
            os.path.join(out_dir, "canvas_depth.png"),
            cmap="inferno",
        )

    return {
        "canvas": canvas,
        "relations": canvas.relations,
        "num_relations": len(canvas.relations),
        "placement": placement,
        "out_dir": out_dir,
    }



class SceneCanvas:
    """The explicit 3D scene scaffold built from generated objects."""

    def __init__(self, painting_c2w: torch.Tensor):
        self.objects: list[dict] = []
        self.relations: list[dict] = []
        self.ground: dict = {"a": 0.0, "b": 0.0, "c": 0.0}
        self.background: Optional[dict] = None
        self.stroke_labels: Optional[torch.Tensor] = None
        self.painting_c2w: torch.Tensor = painting_c2w
        self.scene_stats: dict = {}

    # ---- construction -----------------------------------------------------

    def add_object(self, entry: dict, mask: np.ndarray) -> None:
        """Register one TripoSplat-generated object with its layout metadata."""
        pos = entry["gaussians"]["position"].detach()
        obj = {
            "id": entry["id"],
            "gaussians": entry["gaussians"],
            "centroid": pos.mean(dim=0).tolist(),
            "obb": _obb(pos),
            "num_gaussians": entry["num_gaussians"],
            "mean_depth": entry["mean_depth"],
            "bbox": entry["bbox"],
            "area": entry["area"],
            "mask": mask,
        }
        self.objects.append(obj)

    def set_background(self, background: dict) -> None:
        self.background = background

    # ---- relations ----------------------------------------------------------

    def compute_relations(self, cfg: SceneCanvasConfig) -> list[dict]:
        """Build the spatial-dependency graph between objects (and ground).

        Edge types:
          * ``rests_on(a, b)`` — a's underside is in vertical contact with b's
            upper surface (a is above b), with horizontal overlap;
          * ``rests_on_ground(a, ground)`` — a's underside touches the fitted
            ground plane;
          * ``in_front_of(a, b)`` — a is nearer the camera and their image
            masks overlap (a can occlude b);
          * ``adjacent_to(a, b)`` — nearby laterally without contact.

        Note ``supports(b, a)`` is the inverse reading of ``rests_on(a, b)``
        and is stored as edge attribute ``"inverse": "supports"``.
        """
        rels: list[dict] = []
        K = len(self.objects)
        scene_h = max(1e-6, max(o["obb"]["extent"][1] for o in self.objects)) if K else 1.0
        scene_w = max(1e-6, max(max(o["obb"]["extent"][0], o["obb"]["extent"][2]) for o in self.objects)) if K else 1.0
        self.scene_stats = {"scene_height": scene_h, "scene_width": scene_w}

        for i, obj in enumerate(self.objects):
            # Ground contact.
            cx, cz = obj["centroid"][0], obj["centroid"][2]
            gy = ground_y_at(self.ground, cx, cz)
            gap = gy - obj["obb"]["max"][1]  # >0: object floats above ground
            if abs(gap) < cfg.support_contact_tol * scene_h:
                rels.append(
                    {"type": "rests_on_ground", "a": obj["id"], "b": "ground",
                     "gap": float(gap), "strength": 1.0 - abs(gap) / max(cfg.support_contact_tol * scene_h, 1e-6)}
                )

        for i in range(K):
            for j in range(K):
                if i == j:
                    continue
                a, b = self.objects[i], self.objects[j]
                # --- vertical support: a rests on b ---
                a_top, a_bot = a["obb"]["min"][1], a["obb"]["max"][1]
                b_top, b_bot = b["obb"]["min"][1], b["obb"]["max"][1]
                above = a["centroid"][1] < b["centroid"][1]
                gap = a_bot - b_top  # ~0 when a's underside touches b's top
                ox = _horizontal_overlap_1d(a["obb"]["min"][0], a["obb"]["max"][0], b["obb"]["min"][0], b["obb"]["max"][0])
                oz = _horizontal_overlap_1d(a["obb"]["min"][2], a["obb"]["max"][2], b["obb"]["min"][2], b["obb"]["max"][2])
                if (
                    above
                    and abs(gap) < cfg.support_contact_tol * scene_h
                    and ox > 0.02 * scene_w
                    and oz > 0.02 * scene_w
                ):
                    rels.append(
                        {"type": "rests_on", "a": a["id"], "b": b["id"], "inverse": "supports",
                         "gap": float(gap), "strength": 1.0 - abs(gap) / max(cfg.support_contact_tol * scene_h, 1e-6)}
                    )
                    continue
                # --- occlusion ordering ---
                nearer = a["centroid"][2] < b["centroid"][2]
                ov = _mask_overlap(a["mask"], b["mask"])
                if nearer and ov > cfg.occlusion_min_overlap:
                    rels.append(
                        {"type": "in_front_of", "a": a["id"], "b": b["id"],
                         "inverse": "behind", "overlap": float(ov), "strength": float(ov)}
                    )
                    continue
                # --- lateral adjacency ---
                gx = max(0.0, max(a["obb"]["min"][0] - b["obb"]["max"][0], b["obb"]["min"][0] - a["obb"]["max"][0]))
                gz = max(0.0, max(a["obb"]["min"][2] - b["obb"]["max"][2], b["obb"]["max"][2] if False else b["obb"]["min"][2] - a["obb"]["max"][2]))
                if min(gx, gz) < cfg.adjacency_tol * scene_w and abs(a["centroid"][1] - b["centroid"][1]) < scene_h:
                    rels.append(
                        {"type": "adjacent_to", "a": a["id"], "b": b["id"],
                         "gap": float(min(gx, gz)), "strength": 1.0 - min(gx, gz) / max(cfg.adjacency_tol * scene_w, 1e-6)}
                    )
        self.relations = rels
        return rels

    def snap_objects_to_supports(self, cfg: SceneCanvasConfig) -> dict:
        """Resolve the dependency graph physically: floating objects with a
        ``rests_on_ground`` relation are translated down onto the ground.

        Returns placement diagnostics (number of adjusted objects, total
        displacement). Objects without ground contact keep their painting-
        implied position (they are either supported by other objects or
        airborne scene elements like clouds).
        """
        scene_h = self.scene_stats.get("scene_height", 1.0)
        adjusted = 0
        total_disp = 0.0
        ground_edges = [r for r in self.relations if r["type"] == "rests_on_ground"]
        for r in ground_edges:
            obj = self.objects[r["a"] - 1]
            gap = r["gap"]
            if gap > cfg.support_contact_tol * scene_h * 0.25:
                dy = gap  # translate down (y grows downward)
                obj["gaussians"]["position"] = obj["gaussians"]["position"].detach() + torch.tensor(
                    [0.0, dy, 0.0], device=obj["gaussians"]["position"].device
                )
                obj["centroid"][1] += dy
                obj["obb"]["min"][1] += dy
                obj["obb"]["max"][1] += dy
                adjusted += 1
                total_disp += abs(dy)
        # Recompute relations after snapping (gaps change).
        if adjusted:
            self.compute_relations(cfg)
        return {"adjusted": adjusted, "total_displacement": total_disp}

    # ---- Gaussian composition ------------------------------------------------

    def canvas_gaussians_camera(self) -> dict:
        """All canvas Gaussians in the painting-camera frame (objects + bg)."""
        parts = [o["gaussians"] for o in self.objects if o["num_gaussians"] > 0]
        if self.background is not None and self.background["position"].shape[0] > 0:
            parts.append(self.background)
        if not parts:
            z = torch.zeros(0, 3)
            return {"position": z, "sh_dc": z.clone(), "opacity": torch.zeros(0),
                    "scale": z.clone(), "rotation": torch.zeros(0, 4)}

        def _cat(k):
            return torch.cat([p[k] for p in parts], dim=0)

        g = {k: _cat(k) for k in ("position", "sh_dc", "opacity", "scale", "rotation")}
        # Per-Gaussian object label: 0 = background, i = object id.
        labels = []
        for o in self.objects:
            if o["num_gaussians"] > 0:
                labels.append(torch.full((o["num_gaussians"],), o["id"], dtype=torch.long))
        n_obj = sum(t.shape[0] for t in labels)
        n_bg = g["position"].shape[0] - n_obj
        if n_bg > 0:
            labels.append(torch.zeros(n_bg, dtype=torch.long))
        g["object_label"] = torch.cat(labels) if labels else torch.zeros(0, dtype=torch.long)
        if self.stroke_labels is not None and self.stroke_labels.shape[0] == n_bg + n_obj:
            g["stroke_label"] = self.stroke_labels
        return g

    def world_gaussians(self) -> dict:
        """Canvas Gaussians mapped into the pipeline's world frame."""
        g = self.canvas_gaussians_camera()
        c2w = self.painting_c2w.to(g["position"].device, g["position"].dtype)
        R, t = c2w[:3, :3], c2w[:3, 3]
        g["position"] = g["position"] @ R.T + t.unsqueeze(0)
        return g

    # ---- rendering / depth ------------------------------------------------

    def render(self, c2w: torch.Tensor, H: int, W: int) -> torch.Tensor:
        g = self.world_gaussians()
        return rasterise_gaussians(g, c2w, H, W)

    def canvas_depth(self, H: int, W: int, focal_frac: float = 1.2) -> torch.Tensor:
        """Splat z-buffer depth of the canvas from the painting view, in [0, 1].

        Each Gaussian deposits its depth over a small screen window (radius
        from its projected scale), so the composited depth is hole-free at
        demo resolutions. This is the canvas-composited geometry signal that
        Stage 0 consumes when ``enable_canvas_depth_control`` is on.
        """
        g = self.canvas_gaussians_camera()
        device, dtype = g["position"].device, g["position"].dtype
        f = focal_frac * float(max(H, W))
        cx, cy = float(W) * 0.5, float(H) * 0.5
        pos = g["position"]
        z = pos[:, 2].clamp_min(1e-3)
        u = pos[:, 0] / z * f + cx
        v = pos[:, 1] / z * f + cy
        scale = (g["scale"].mean(dim=-1) * f / z).clamp(1.0, 6.0)

        # Splat z: far-to-near writes so the nearest surface wins per pixel.
        order = torch.argsort(-z)
        u, v, z_s, scale = u[order], v[order], z[order], scale[order]
        ui = u.round().long()
        vi = v.round().long()
        keep = (ui >= 0) & (ui < W) & (vi >= 0) & (vi < H)
        ui, vi, z_s, scale = ui[keep], vi[keep], z_s[keep], scale[keep]
        r = scale.round().long().clamp_min(0)
        depth = torch.zeros(H, W, device=device, dtype=dtype)

        # Group by radius so each batch is a rectangular window.
        for rad in sorted(set(r.tolist())):
            sel = r == rad
            if not bool(sel.any()):
                continue
            dy, dx = torch.meshgrid(
                torch.arange(-rad, rad + 1, device=device),
                torch.arange(-rad, rad + 1, device=device),
                indexing="ij",
            )
            xx = ui[sel].unsqueeze(1) + dx.reshape(1, -1)
            yy = vi[sel].unsqueeze(1) + dy.reshape(1, -1)
            inb = (xx >= 0) & (xx < W) & (yy >= 0) & (yy < H)
            zz = z_s[sel].unsqueeze(1).expand_as(xx)
            flat = (yy.clamp(0, H - 1) * W + xx.clamp(0, W - 1)).reshape(-1)
            depth.reshape(-1)[flat[inb.reshape(-1)]] = zz.reshape(-1)[inb.reshape(-1)]

        # Residual holes (pixels no window touched): dilate, then median fill.
        for _ in range(6):
            holes = depth <= 1e-6
            if not bool(holes.any()):
                break
            dil = -torch.nn.functional.max_pool2d(
                (-depth).unsqueeze(0), 3, stride=1, padding=1
            ).squeeze(0)
            depth = torch.where(holes & (dil > 1e-6), dil, depth)
        if bool((depth <= 1e-6).any()):
            valid = depth > 1e-6
            med = depth[valid].median() if bool(valid.any()) else torch.tensor(2.2, device=device)
            depth = torch.where(depth <= 1e-6, med, depth)

        return ((depth - 0.2) / 4.0).clamp(0.0, 1.0)

    # ---- persistence -------------------------------------------------------

    def save(self, out_dir: str) -> None:
        os.makedirs(out_dir, exist_ok=True)
        g = self.canvas_gaussians_camera()
        np.savez_compressed(
            os.path.join(out_dir, "canvas.npz"),
            position=g["position"].cpu().numpy(),
            sh_dc=g["sh_dc"].cpu().numpy(),
            opacity=g["opacity"].cpu().numpy(),
            scale=g["scale"].cpu().numpy(),
            rotation=g["rotation"].cpu().numpy(),
            object_label=g["object_label"].cpu().numpy(),
            stroke_label=(
                self.stroke_labels.cpu().numpy()
                if self.stroke_labels is not None
                else np.zeros(g["position"].shape[0], dtype=np.int64)
            ),
            painting_c2w=self.painting_c2w.cpu().numpy(),
            ground=np.array([self.ground["a"], self.ground["b"], self.ground["c"]]),
            scene_stats=json.dumps(self.scene_stats),
        )
        with open(os.path.join(out_dir, "relations.json"), "w") as f:
            json.dump(
                {
                    "relations": [
                        {k: v for k, v in r.items() if k != "mask"} for r in self.relations
                    ],
                    "ground": self.ground,
                    "objects": [
                        {"id": o["id"], "centroid": o["centroid"], "obb": o["obb"],
                         "num_gaussians": o["num_gaussians"], "area": o["area"]}
                        for o in self.objects
                    ],
                },
                f,
                indent=2,
            )



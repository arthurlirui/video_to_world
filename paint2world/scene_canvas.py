# Canvas-anchored GS training (Stage 3.2b)
# ---------------------------------------------------------------------------

def _se3_delta_apply(
    positions: torch.Tensor,  # (N, 3) camera-space base positions
    centroid: torch.Tensor,  # (3,) object centroid
    delta_t: torch.Tensor,  # (3,) learnable translation
    delta_yaw: torch.Tensor,  # (,) learnable yaw
) -> torch.Tensor:
    """Apply a per-object rigid delta: yaw about the centroid + translation."""
    c, s = torch.cos(delta_yaw), torch.sin(delta_yaw)
    # Rotation about y (camera 'down' axis).
    R = torch.stack(
        [
            torch.stack([c, torch.zeros_like(c), s]),
            torch.stack([torch.zeros_like(c), torch.ones_like(c), torch.zeros_like(c)]),
            torch.stack([-s, torch.zeros_like(c), c]),
        ]
    )
    return (positions - centroid) @ R.T + centroid + delta_t.unsqueeze(0)


def train_canvas_anchored_gs(
    canvas: SceneCanvas,
    canvas_cfg: SceneCanvasConfig,
    gs_cfg: StrokeCoherentGSConfig,
    frame_images: torch.Tensor,  # (N, 3, H, W), world-frame cameras
    frame_c2w_list: list[torch.Tensor],
    painting_rgb: torch.Tensor,
    painting_c2w: torch.Tensor,
    out_dir: str,
    num_iters: int = 300,
    lr: float = 5e-3,
    device: Optional[torch.device] = None,
) -> dict:
    """Stage 3.2b: canvas-anchored GS training with object-rigid anchors.

    Each object's Gaussians move rigidly via a learnable (translation, yaw)
    delta; background Gaussians move via one shared delta; SH colours and
    opacities are per-Gaussian free parameters. Losses: rendering L1 on the
    generated frames, painting-view reconstruction, stroke coherence, and the
    relation-preservation loss on support contacts.

    Returns the trained world-frame Gaussians plus diagnostics
    (per-object deltas, relation-gap drift).
    """
    device = device or torch.device("cpu")
    dtype = torch.float32
    g = {
        k: (v.to(device=device, dtype=dtype) if torch.is_floating_point(v) else v.to(device))
        for k, v in canvas.canvas_gaussians_camera().items()
    }
    n_total = g["position"].shape[0]
    if n_total == 0:
        return {"position": torch.zeros(0, 3), "sh_dc": torch.zeros(0, 3),
                "opacity": torch.zeros(0), "scale": torch.zeros(0, 3),
                "rotation": torch.zeros(0, 4), "object_label": torch.zeros(0, dtype=torch.long),
                "relation_gap_drift": 0.0, "object_deltas": {}}

    obj_ids = sorted(set(int(x) for x in g["object_label"].tolist()))
    num_obj = len(obj_ids)
    id_to_k = {oid: k for k, oid in enumerate(obj_ids)}
    centroids = torch.zeros(num_obj, 3, device=device, dtype=dtype)
    for oid in obj_ids:
        m = g["object_label"] == oid
        if int(m.sum().item()) > 0:
            centroids[id_to_k[oid]] = g["position"][m].mean(dim=0).detach()
        else:
            centroids[id_to_k[oid]] = torch.zeros(3, device=device, dtype=dtype)

    # Learnable parameters.
    delta_t = torch.zeros(num_obj, 3, device=device, dtype=dtype, requires_grad=True)
    delta_yaw = torch.zeros(num_obj, device=device, dtype=dtype, requires_grad=True)
    sh = g["sh_dc"].clone().requires_grad_(True)
    opacity = g["opacity"].clone().requires_grad_(True)

    # Base relation gaps (camera space): (object id -> gap) for ground contacts
    # and (a, b) pair gaps for rests_on.
    support_gaps = []
    scene_h = canvas.scene_stats.get("scene_height", 1.0)
    for r in canvas.relations:
        if r["type"] == "rests_on_ground":
            support_gaps.append((r["a"], "ground", r["gap"]))
        elif r["type"] == "rests_on":
            support_gaps.append((r["a"], r["b"], r["gap"]))
    support_gaps_t = torch.tensor([x[2] for x in support_gaps], device=device, dtype=dtype)

    base_pos = g["position"].detach()
    label_t = g["object_label"].detach()
    c2w = canvas.painting_c2w.to(device=device, dtype=dtype)
    R_w, t_w = c2w[:3, :3], c2w[:3, 3]

    def world_positions() -> torch.Tensor:
        out = torch.empty_like(base_pos)
        for oid in obj_ids:
            m = label_t == oid
            if int(m.sum().item()) == 0:
                continue
            k = id_to_k[oid]
            moved = _se3_delta_apply(base_pos[m], centroids[k], delta_t[k], delta_yaw[k])
            out = out.index_copy(0, torch.nonzero(m, as_tuple=True)[0], moved)
        return out @ R_w.T + t_w.unsqueeze(0)

    def relation_gap_drift() -> torch.Tensor:
        """|current gap - initial gap| over support contacts (camera space)."""
        if not support_gaps:
            return torch.zeros((), device=device, dtype=dtype)
        pos = torch.empty_like(base_pos)
        for oid in obj_ids:
            m = label_t == oid
            if int(m.sum().item()) == 0:
                continue
            k = id_to_k[oid]
            moved = _se3_delta_apply(base_pos[m], centroids[k], delta_t[k], delta_yaw[k])
            pos = pos.index_copy(0, torch.nonzero(m, as_tuple=True)[0], moved)
        drifts = []
        for (a, b, _gap), g0 in zip(support_gaps, support_gaps_t):
            ma = label_t == a
            if int(ma.sum().item()) == 0:
                continue
            bottom = pos[ma][:, 1].max()
            if b == "ground":
                gy = ground_y_at(canvas.ground, centroids[id_to_k[a]][0].item(), centroids[id_to_k[a]][2].item())
                drifts.append(((gy - bottom) - g0).abs())
            else:
                mb = label_t == b
                if int(mb.sum().item()) == 0:
                    continue
                top = pos[mb][:, 1].min()
                drifts.append(((bottom - top) - g0).abs())
        if not drifts:
            return torch.zeros((), device=device, dtype=dtype)
        return torch.stack(drifts).mean()

    opt = torch.optim.Adam([delta_t, delta_yaw, sh, opacity], lr=lr)
    N_frames = frame_images.shape[0]
    H, W = frame_images.shape[-2:]
    painting_rgb = painting_rgb.to(device=device, dtype=dtype)
    stroke_labels = g.get(
        "stroke_label",
        canvas.stroke_labels.to(device) if canvas.stroke_labels is not None
        else torch.zeros(n_total, dtype=torch.long, device=device),
    )
    if stroke_labels.shape[0] != n_total:
        stroke_labels = torch.zeros(n_total, dtype=torch.long, device=device)

    from .stroke_coherent_gs import _stroke_coherence_loss_direct

    for it in range(num_iters):
        opt.zero_grad()
        g_t = {
            "position": world_positions(),
            "sh_dc": sh,
            "opacity": opacity,
            "scale": g["scale"],
            "rotation": g["rotation"],
            "stroke_label": stroke_labels,
        }
        loss = torch.zeros((), device=device, dtype=dtype)
        i = int(torch.randint(0, N_frames, (1,)).item())
        rendered = rasterise_gaussians(g_t, frame_c2w_list[i], H, W)
        target = frame_images[i].to(device=device, dtype=dtype)
        loss = loss + (rendered - target).abs().mean()

        if gs_cfg.painting_view_loss_weight > 0:
            rendered_painting = rasterise_gaussians(g_t, painting_c2w, H, W)
            loss = loss + gs_cfg.painting_view_loss_weight * (rendered_painting - painting_rgb).abs().mean()

        if gs_cfg.enable_stroke_coherence and gs_cfg.stroke_coherence_weight > 0:
            loss = loss + gs_cfg.stroke_coherence_weight * _stroke_coherence_loss_direct(
                sh, stroke_labels, gs_cfg
            )

        if canvas_cfg.relation_preservation_weight > 0:
            loss = loss + canvas_cfg.relation_preservation_weight * (
                relation_gap_drift() / max(scene_h, 1e-6)
            )

        loss = loss + 1e-2 * torch.sigmoid(opacity).mean()
        loss.backward()
        opt.step()

    out = {
        "position": world_positions().detach(),
        "sh_dc": sh.detach(),
        "opacity": opacity.detach(),
        "scale": g["scale"],
        "rotation": g["rotation"],
        "object_label": label_t,
        "stroke_label": stroke_labels,
    }
    with torch.no_grad():
        out["relation_gap_drift"] = float(relation_gap_drift().item())
    out["object_deltas"] = {
        int(oid): {
            "translation": delta_t[id_to_k[oid]].detach().cpu().tolist(),
            "yaw_deg": float(torch.rad2deg(delta_yaw[id_to_k[oid]]).item()),
        }
        for oid in obj_ids
    }

    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
        np.savez_compressed(
            os.path.join(out_dir, "gaussians.npz"),
            position=out["position"].cpu().numpy(),
            sh_dc=out["sh_dc"].cpu().numpy(),
            opacity=out["opacity"].cpu().numpy(),
            scale=out["scale"].cpu().numpy(),
            rotation=out["rotation"].cpu().numpy(),
            object_label=out["object_label"].cpu().numpy(),
            stroke_label=out["stroke_label"].cpu().numpy(),
            relation_gap_drift=out["relation_gap_drift"],
        )
        from .stroke_coherent_gs import _save_image

        _save_image(
            rasterise_gaussians(out, painting_c2w, H, W).clamp(0, 1),
            os.path.join(out_dir, "render_painting_view.png"),
        )
    return out

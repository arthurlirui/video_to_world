def _plot_layout(canvas: SceneCanvas, out_path: str) -> None:
    """Top-down (x-z) and side (x-y) layout plots with relation edges."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 5))
    ids = [o["id"] for o in canvas.objects]
    colors = plt.cm.tab20(np.linspace(0, 1, max(len(ids), 1)))

    def _draw_boxes(ax, mode):
        for o in canvas.objects:
            mn, mx = o["obb"]["min"], o["obb"]["max"]
            if mode == "top":
                rect = plt.Rectangle((mn[0], mn[2]), mx[0] - mn[0], mx[2] - mn[2],
                                     fill=True, alpha=0.35, color=colors[o["id"] - 1])
            else:
                rect = plt.Rectangle((mn[0], mn[1]), mx[0] - mn[0], mx[1] - mn[1],
                                     fill=True, alpha=0.35, color=colors[o["id"] - 1])
            ax.add_patch(rect)
            c = o["centroid"]
            cx, cy = (c[0], c[2]) if mode == "top" else (c[0], c[1])
            ax.text(cx, cy, str(o["id"]), fontsize=8, ha="center", va="center")

    for mode, ax, (xl, yl) in (("top", axes[0], ("x", "z")), ("side", axes[1], ("x", "y"))):
        _draw_boxes(ax, mode)
        # Relation edges.
        for r in canvas.relations:
            if r["b"] == "ground":
                continue
            pa = canvas.objects[r["a"] - 1]["centroid"]
            pb = canvas.objects[r["b"] - 1]["centroid"]
            xa, ya = (pa[0], pa[2]) if mode == "top" else (pa[0], pa[1])
            xb, yb = (pb[0], pb[2]) if mode == "top" else (pb[0], pb[1])
            if mode == "top" and r["type"] in ("rests_on", "rests_on_ground"):
                continue  # vertical relations invisible from the top
            style = {
                "rests_on": "-", "in_front_of": "--", "adjacent_to": ":",
            }.get(r["type"], "-")
            ax.plot([xa, xb], [ya, yb], style, color="gray", linewidth=0.8, alpha=0.7)
        ax.set_xlabel(xl)
        ax.set_ylabel(yl)
        ax.set_title(f"{mode} view")
        ax.set_aspect("equal")
    fig.suptitle("Scene canvas: object layout + spatial dependencies")
    fig.tight_layout()
    fig.savefig(out_path, dpi=120)
    plt.close(fig)


